-- ------------------------------------------------------------
-- content_record.quote —— 每篇输出可以附一句「语录」
--
-- 设计取舍：
--   最初做了一张独立的 my_quote 表（收集喜欢的话），后来改成
--   语录归属于具体一篇输出 —— 它本来就是从这篇文章里提炼出来的，
--   单独存会变成又一个「要维护的列表」。挂在文章上：写的时候顺手记一句，
--   看列表时以引用样式回显，成本最低，也不会多出一个空列表要照顾。
--
--   所以这里建列，并清掉上一版遗留的 my_quote 表。
-- ------------------------------------------------------------
ALTER TABLE content_record ADD COLUMN IF NOT EXISTS quote TEXT;

COMMENT ON COLUMN content_record.quote IS '本篇输出的一句话提炼 / 语录（可选）';

-- 清理上一版遗留的独立语录表（该功能已并入 content_record.quote）
DROP TABLE IF EXISTS my_quote;
